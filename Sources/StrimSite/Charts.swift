    func memorySVG(standalone: Bool) -> String {
        let mem = H["memory"]
        var groups: [(label: String, vals: PyJSON, hl: Bool)] = []
        if let w = mem?["whole_run"] { groups.append(("Peak over the whole run", w, true)) }
