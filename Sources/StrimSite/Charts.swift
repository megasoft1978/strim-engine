func fnum(_ v: Double) -> String {
    var s = fmtFixed(v, 1)
    if s.hasSuffix(".0") { s.removeLast(2) }
    return s
}

func fx(_ v: Double) -> String { fmtFixed(v, v >= 10 ? 1 : 2) + "\u{00d7}" }

extension SiteBuilder {
