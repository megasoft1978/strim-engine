        var body = ""
        for r in rows {
            body += "<tr><th scope=\"row\">\(esc(r["label"]?.pyStr ?? ""))<span class=\"sub\">\(esc(r["group"]?.pyStr ?? ""))</span></th>"
            for e in ENGINES {
                let s = r[e]?["s"]?.pyStr ?? "unknown"
                let n = r[e]?["n"]?.pyStr ?? ""
                let lab = SiteBuilder.STATUS_LABEL[s] ?? s
                body += "<td>" + (s == "info" ? "" : "<span class=\"st st-\(s)\">\(esc(lab))</span>") + (n.isEmpty ? "" : "<span class=\"fn\">\(esc(n))</span>") + "</td>"
            }
            body += "</tr>"
        }
        return "<div class=\"tablewrap\" tabindex=\"0\" role=\"region\" aria-label=\"Functionality matrix\"><table class=\"feat\"><caption>Functionality matrix (verified 2026-10-28)</caption>"
            + "<thead><tr><th scope=\"col\">Feature</th><th scope=\"col\">Strim</th><th scope=\"col\">rapid-mlx \(esc(F["versions"]?["rapid-mlx"]?.pyStr ?? ""))</th><th scope=\"col\">mlx-vlm \(esc(F["versions"]?["mlx-vlm"]?.pyStr ?? ""))</th></tr></thead><tbody>\(body)</tbody></table></div>"
    }

    func featureCounts() -> String {
        let rows = (F["rows"]?.arr ?? []).filter { $0["strim"]?["s"]?.str != "info" }
        var parts: [String] = []
        for e in ENGINES {
            let yes = rows.filter { $0[e]?["s"]?.str == "yes" }.count
            parts.append("\(ENG_LABEL[e] ?? e) \(yes) of \(rows.count)")
        }
        return parts.joined(separator: ", ")
    }

    func featuresMarkdown() -> String {
        var out = ["| Feature | Strim | rapid-mlx | mlx-vlm |", "|---|:---:|:---:|:---:|"]
        for r in F["rows"]?.arr ?? [] where r["readme"]?.truthy ?? false {
            var line = "| \(r["label"]?.pyStr ?? "") |"
            for e in ENGINES {
                let s = r[e]?["s"]?.pyStr ?? "unknown"
                line += " " + (s == "info" ? (r[e]?["n"]?.pyStr ?? "") : (SiteBuilder.STATUS_LABEL[s] ?? s)) + " |"
            }
            out.append(line)
        }
        return out.joined(separator: "\n")
    }
