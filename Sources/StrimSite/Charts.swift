            body += "<title>\(esc(tip))</title></g>"
        }
        let h = bottom + 56
        let tot = H["scoreboard"]?["total"]
        func line(_ rv: String) -> String {
            "vs \(rv): \(tot?[rv]?["WIN"]?.pyStr ?? "0") wins, \(tot?[rv]?["TIE"]?.pyStr ?? "0") ties, \(tot?[rv]?["LOSS"]?.pyStr ?? "0") losses"
