            }
            inner += "</g>"
            y += gh
            if gi == 0 { y += 6 }
        }
        let bottom = y
        // grid and abort limit
        var t = 0.0
        while t <= maxV {
            body += "<line class=\"g\" x1=\"\(fnum(sx(t)))\" x2=\"\(fnum(sx(t)))\" y1=\"\(fnum(y0 - 4))\" y2=\"\(fnum(bottom))\"/>"
            body += "<text class=\"m s c\" x=\"\(fnum(sx(t)))\" y=\"\(fnum(bottom + 13))\">\(fnum(t))</text>"
