import Foundation
import Testing
@testable import StrimSite

/// WCAG 2.x contrast for site text (4.5:1) and large text/marks (3:1), across both themes.
@Suite struct SiteContrastTests {
    struct RGBA { var r: Double, g: Double, b: Double, a: Double }

    static func parse(_ v: String) -> RGBA? {
        let s = v.trimmingCharacters(in: .whitespaces)
        guard s.hasPrefix("#") else { return nil }
        var h = String(s.dropFirst())
        if h.count == 3 { h = h.map { "\($0)\($0)" }.joined() }
        guard h.count == 6, let n = Int(h, radix: 16) else { return nil }
        return RGBA(r: Double((n >> 16) & 255), g: Double((n >> 8) & 255), b: Double(n & 255), a: 1)
    }

    static func luminance(_ c: RGBA) -> Double {
        func ch(_ v: Double) -> Double { let x = v / 255; return x <= 0.03928 ? x / 12.92 : pow((x + 0.055) / 1.055, 2.4) }
        return 0.2126 * ch(c.r) + 0.7152 * ch(c.g) + 0.0722 * ch(c.b)
    }

    static func ratio(_ a: RGBA, _ b: RGBA) -> Double {
        let la = luminance(a), lb = luminance(b)
        return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)
    }

    static func tokens(_ css: String, _ selector: String, prefix: String) -> [String: String] {
        guard let r = css.range(of: selector) else { return [:] }
        let rest = css[r.upperBound...]
        guard let end = rest.firstIndex(of: "}") else { return [:] }
        var out: [String: String] = [:]
        for decl in rest[..<end].split(separator: ";") {
            let kv = decl.split(separator: ":", maxSplits: 1).map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            if kv.count == 2, kv[0].hasPrefix(prefix) { out[kv[0]] = kv[1] }
        }
        return out
    }

    struct Theme { var name: String; var site: [String: String]; var chart: [String: String] }

    static func themes() -> [Theme] {
        let css = readString(repoRoot + "/site/assets/style.css")
        let dark = tokens(css, ":root {", prefix: "--")
        let light = tokens(css, ":root[data-theme=\"light\"] {", prefix: "--")
        let chartLight = tokens(css, "/* hv:begin (generated by strim site build, do not edit) */\n.hv{", prefix: "--hv-")
        let chartDark = tokens(css, ":root[data-theme=\"dark\"] .hv{", prefix: "--hv-")
        return [Theme(name: "dark", site: dark, chart: chartDark), Theme(name: "light", site: light, chart: chartLight)]
    }

    static func col(_ t: [String: String], _ k: String) -> RGBA {
        guard let v = t[k], let c = parse(v) else { Issue.record("no colour \(k)"); return RGBA(r: 0, g: 0, b: 0, a: 1) }
        return c
    }

    @Test func siteColoursMeetWCAGInBothThemes() {
        for t in Self.themes() {
            let s = t.site
            #expect(s.count >= 15, "\(t.name): site tokens not found")
            let backgrounds = ["--bg", "--bg-2", "--glass-2", "--code-bg"]
            // Body, muted, link/accent, badge, and status text on every site surface.
            for fg in ["--fg", "--muted", "--link", "--warn", "--pend"] {
                for bg in backgrounds {
                    let r = Self.ratio(Self.col(s, fg), Self.col(s, bg))
                    #expect(r >= 4.5, "\(t.name): \(fg) on \(bg) is \(String(format: "%.2f", r)):1; needs 4.5")
                }
            }
            let btnRatio = Self.ratio(Self.col(s, "--btn-fg"), Self.col(s, "--btn"))
            #expect(btnRatio >= 4.5, "\(t.name): button text is \(String(format: "%.2f", btnRatio)):1")
            let accent = Self.col(s, "--a")
            for bg in backgrounds.prefix(3) {
                let r = Self.ratio(accent, Self.col(s, bg))
                #expect(r >= 3, "\(t.name): accent numeral/mark on \(bg) is \(String(format: "%.2f", r)):1; needs 3")
            }
            let dashed = Self.ratio(Self.col(s, "--muted"), Self.col(s, "--glass"))
            #expect(dashed >= 4.5, "\(t.name): dashed-card text is \(String(format: "%.2f", dashed)):1")
            let focus = Self.ratio(Self.col(s, "--focus"), Self.col(s, "--bg"))
            #expect(focus >= 3, "\(t.name): focus ring is \(String(format: "%.2f", focus)):1")
        }
    }

    @Test func chartColoursMeetWCAGInBothThemes() {
        for t in Self.themes() {
            let h = t.chart
            #expect(h.count >= 20, "\(t.name): chart tokens not found")
            let bg = Self.col(h, "--hv-bg")
            for fg in ["--hv-fg", "--hv-mu", "--hv-w", "--hv-l", "--hv-t"] {
                let r = Self.ratio(Self.col(h, fg), bg)
                #expect(r >= 4.5, "\(t.name): chart text \(fg) on chart background is \(String(format: "%.2f", r)):1")
            }
            // Engine marks (rivals are neutral greys; Strim is the sole accent) must remain legible.
            for mark in ["--hv-s", "--hv-r", "--hv-v", "--hv-q", "--hv-p", "--hv-a"] {
                let r = Self.ratio(Self.col(h, mark), bg)
                #expect(r >= 3, "\(t.name): chart mark \(mark) on chart background is \(String(format: "%.2f", r)):1")
            }
            let badge = Self.ratio(Self.col(h, "--hv-l"), Self.col(h, "--hv-lb"))
            #expect(badge >= 4.5, "\(t.name): loss badge text is \(String(format: "%.2f", badge)):1")
        }
    }

    @Test func quietModernRemovesGradientTextAndAuroraTexture() {
        let css = readString(repoRoot + "/site/assets/style.css").lowercased()
        #expect(!css.contains("gradient-text") && !css.contains("gradienttext"), "gradient text classes remain")
        #expect(!css.contains("aurora") && !css.contains("grain"), "aurora or grain CSS remains")
    }
}
