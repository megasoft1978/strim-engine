import Foundation
import Testing
@testable import StrimSite

/// WCAG 2.x contrast of every text/background pair of the site, computed from the colours in site/assets/style.css in both themes.
/// Body text needs 4.5:1, large text (the gradient headlines and numerals, at least 24 px or 19 px bold) and graphics need 3:1.
@Suite struct SiteContrastTests {
    struct RGBA { var r: Double, g: Double, b: Double, a: Double }

    static func parse(_ v: String) -> RGBA? {
        let s = v.trimmingCharacters(in: .whitespaces)
        if s.hasPrefix("#") {
            var h = String(s.dropFirst())
            if h.count == 3 { h = h.map { "\($0)\($0)" }.joined() }
            guard h.count == 6, let n = Int(h, radix: 16) else { return nil }
            return RGBA(r: Double((n >> 16) & 255), g: Double((n >> 8) & 255), b: Double(n & 255), a: 1)
        }
        if s.hasPrefix("rgba(") || s.hasPrefix("rgb(") {
            let inner = s.drop(while: { $0 != "(" }).dropFirst().dropLast()
            let p = inner.split(separator: ",").map { Double($0.trimmingCharacters(in: .whitespaces)) ?? 0 }
            guard p.count >= 3 else { return nil }
            return RGBA(r: p[0], g: p[1], b: p[2], a: p.count > 3 ? p[3] : 1)
        }
        return nil
    }

    /// Source-over compositing of `top` on an opaque `bottom`.
    static func over(_ top: RGBA, _ bottom: RGBA) -> RGBA {
        RGBA(r: top.r * top.a + bottom.r * (1 - top.a), g: top.g * top.a + bottom.g * (1 - top.a), b: top.b * top.a + bottom.b * (1 - top.a), a: 1)
    }

    static func luminance(_ c: RGBA) -> Double {
        func ch(_ v: Double) -> Double { let x = v / 255; return x <= 0.03928 ? x / 12.92 : pow((x + 0.055) / 1.055, 2.4) }
        return 0.2126 * ch(c.r) + 0.7152 * ch(c.g) + 0.0722 * ch(c.b)
    }

    static func ratio(_ a: RGBA, _ b: RGBA) -> Double {
        let la = luminance(a), lb = luminance(b)
        return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)
    }

    /// `--name: value` pairs of the first CSS block whose selector line starts with `selector`.
    static func tokens(_ css: String, _ selector: String, prefix: String) -> [String: String] {
        guard let r = css.range(of: selector) else { return [:] }
        let rest = css[r.upperBound...]
        guard let end = rest.firstIndex(of: "}") else { return [:] }
        var out: [String: String] = [:]
        for decl in rest[..<end].split(separator: ";") {
            let kv = decl.split(separator: ":", maxSplits: 1).map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            if kv.count == 2, kv[0].hasPrefix(prefix) { out[kv[0]] = kv[1] }
        }
        return out
    }

    struct Theme { var name: String; var site: [String: String]; var hv: [String: String] }

    static func themes() -> [Theme] {
        let css = readString(repoRoot + "/site/assets/style.css")
        let dark = tokens(css, ":root {", prefix: "--")
        let light = tokens(css, ":root[data-theme=\"light\"] {", prefix: "--")
        let hvLight = tokens(css, "/* hv:begin (generated by strim site build, do not edit) */\n.hv{", prefix: "--hv-")
        let hvDark = tokens(css, ":root[data-theme=\"dark\"] .hv{", prefix: "--hv-")
        return [Theme(name: "dark", site: dark, hv: hvDark), Theme(name: "light", site: light, hv: hvLight)]
    }

    static func col(_ t: [String: String], _ k: String) -> RGBA {
        guard let v = t[k], let c = parse(v) else { Issue.record("no colour \(k)"); return RGBA(r: 0, g: 0, b: 0, a: 1) }
        return c
    }

    @Test func parsesAndComputesKnownRatios() {
        #expect(abs(Self.ratio(Self.parse("#000000")!, Self.parse("#ffffff")!) - 21) < 1e-9)
        #expect(abs(Self.ratio(Self.parse("#777777")!, Self.parse("#ffffff")!) - 4.48) < 0.01)
        let c = Self.over(RGBA(r: 255, g: 255, b: 255, a: 0.5), RGBA(r: 0, g: 0, b: 0, a: 1))
        #expect(abs(c.r - 127.5) < 1e-9)
    }

    @Test func siteColoursMeetWCAGInBothThemes() {
        for t in Self.themes() {
            let s = t.site
            #expect(s.count > 15, "\(t.name): site tokens not found")
            let bg = Self.col(s, "--bg")
            let glass = Self.over(Self.col(s, "--glass"), bg)
            let glass2 = Self.over(Self.col(s, "--glass-2"), bg)
            let code = Self.over(Self.col(s, "--code-bg"), glass)
            let surfaces: [(String, RGBA)] = [("bg", bg), ("glass", glass), ("glass-2", glass2), ("code", code), ("bg-2", Self.col(s, "--bg-2"))]
            // body text, small text, badges, dashed-card text and links, on every surface they can sit on
            for token in ["--fg", "--muted", "--link", "--warn", "--pend"] {
                for (n, surf) in surfaces {
                    let r = Self.ratio(Self.col(s, token), surf)
                    #expect(r >= 4.5, "\(t.name): \(token) on \(n) is \(String(format: "%.2f", r)):1, needs 4.5")
                }
            }
            // buttons and the selected tab
            let btn = Self.col(s, "--btn"), btnfg = Self.col(s, "--btn-fg")
            #expect(Self.ratio(btnfg, btn) >= 4.5, "\(t.name): button text \(String(format: "%.2f", Self.ratio(btnfg, btn)))")
            #expect(Self.ratio(bg, Self.col(s, "--fg")) >= 4.5, "\(t.name): selected tab text")
            // gradient headlines and numerals are large text: every stop on the page background and on glass
            for stop in ["--a", "--b", "--c"] {
                for (n, surf) in surfaces.prefix(3) {
                    let r = Self.ratio(Self.col(s, stop), surf)
                    #expect(r >= 3, "\(t.name): gradient stop \(stop) on \(n) is \(String(format: "%.2f", r)):1, needs 3 (large text)")
                }
            }
            // focus ring and rules as graphics
            #expect(Self.ratio(Self.col(s, "--focus"), bg) >= 3, "\(t.name): focus ring")
            // text over the hero aurora blobs (opacity .3 in dark, .16 in light, see .aurora i in style.css), at the blob's strongest point
            let alpha = t.name.lowercased().contains("light") ? 0.16 : 0.3
            for blob in ["--a", "--c"] {
                var c = Self.col(s, blob); c.a = alpha
                let under = Self.over(c, bg)
                for token in ["--fg", "--muted", "--link"] {
                    let r = Self.ratio(Self.col(s, token), under)
                    #expect(r >= 4.5, "\(t.name): \(token) over the \(blob) aurora blob is \(String(format: "%.2f", r)):1")
                }
            }
            // the muted large numerals of a loss card
            #expect(Self.ratio(Self.col(s, "--muted"), glass) >= 3)
        }
    }

    @Test func chartColoursMeetWCAGInBothThemes() {
        for t in Self.themes() {
            let h = t.hv, s = t.site
            #expect(h.count > 12, "\(t.name): chart tokens not found")
            let bg = Self.col(s, "--bg")
            let page = Self.over(Self.col(s, "--glass"), bg)
            // standalone charts carry their own night background (--hv-bg of the dark palette); the page charts sit on glass
            let grounds: [(String, RGBA)] = t.name == "dark" ? [("page glass", page), ("standalone card", Self.col(h, "--hv-bg"))] : [("page glass", page)]
            for (gn, g) in grounds {
                for token in ["--hv-fg", "--hv-mu"] {
                    #expect(Self.ratio(Self.col(h, token), g) >= 4.5, "\(t.name): chart text \(token) on \(gn) is \(String(format: "%.2f", Self.ratio(Self.col(h, token), g)))")
                }
                for token in ["--hv-s", "--hv-r", "--hv-v", "--hv-a", "--hv-b", "--hv-c"] {
                    #expect(Self.ratio(Self.col(h, token), g) >= 3, "\(t.name): chart mark \(token) on \(gn) is \(String(format: "%.2f", Self.ratio(Self.col(h, token), g)))")
                }
            }
            // verdict badges: text on its own fill
            for (fg, fill) in [("--hv-w", "--hv-wb"), ("--hv-l", "--hv-lb"), ("--hv-t", "--hv-tb")] {
                let r = Self.ratio(Self.col(h, fg), Self.over(Self.col(h, fill), page))
                #expect(r >= 4.5, "\(t.name): badge \(fg) on \(fill) is \(String(format: "%.2f", r)):1")
            }
        }
    }
}
